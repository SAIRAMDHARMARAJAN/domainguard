-- DomainGuard v7 / 04: Gold, what the API, dashboard and emails read.
USE DATABASE DOMAINGUARD;

-- One verdict per (domain, company). FIRST_FLAGGED_AT is set once and never overwritten.
CREATE TABLE IF NOT EXISTS GOLD.DOMAIN_VERDICT (
  DOMAIN              STRING,
  COMPANY_ID          STRING,
  SCORE               NUMBER,
  CLASSIFICATION      STRING,   -- ALLOWLISTED | LOW | SUSPICIOUS | HIGH_RISK | DANGEROUS
  MATCHED_BRAND       STRING,
  MATCH_TYPE          STRING,
  SIMILARITY          NUMBER,
  EVIDENCE            VARIANT,  -- list of plain-language reasons
  BREAKDOWN           VARIANT,  -- {"name_similarity": 19, ...}
  IS_ON_BLOCKLIST     BOOLEAN,
  BLOCKLIST_SOURCES   VARIANT,
  FIRST_SEEN_AT       TIMESTAMP_NTZ,
  FIRST_LISTED_AT     TIMESTAMP_NTZ,
  REGISTERED_AT       TIMESTAMP_NTZ,
  AGE_DAYS            FLOAT,
  FIRST_FLAGGED_AT    TIMESTAMP_NTZ,
  LAST_EVALUATED_AT   TIMESTAMP_NTZ,
  SCORING_VERSION     STRING,
  PRIMARY KEY (DOMAIN, COMPANY_ID)
);

-- Plain-language explanation per company, domain and language. VERDICT_SCORE says which score it explains.
CREATE TABLE IF NOT EXISTS GOLD.DOMAIN_BRIEFS (
  DOMAIN         STRING,
  COMPANY_ID     STRING,
  LANGUAGE       STRING,
  SUMMARY        STRING,
  REASONS        VARIANT,
  ADVICE         STRING,
  SOURCE         STRING,       -- llm | template
  MODEL_NAME     STRING,
  VERDICT_SCORE  NUMBER,
  CREATED_AT     TIMESTAMP_NTZ,
  PRIMARY KEY (DOMAIN, COMPANY_ID, LANGUAGE)
);

-- Abuse-report drafts. Nothing in DomainGuard sends them; SENT means an analyst submitted one by hand.
CREATE TABLE IF NOT EXISTS GOLD.TAKEDOWN_DRAFTS (
  DRAFT_ID           STRING PRIMARY KEY,
  DOMAIN             STRING,
  COMPANY_ID         STRING,
  ANALYST_EMAIL      STRING,
  ANALYST_NAME       STRING,
  DRAFT_TEXT         STRING,
  SUBJECT            STRING,
  ABUSE_PROVIDER     STRING,   -- registrar | hoster | other
  STATUS             STRING,   -- DRAFT | APPROVED | REJECTED | EXPORTED | SENT
  CREATED_AT         TIMESTAMP_NTZ,
  APPROVED_AT        TIMESTAMP_NTZ,
  EXPORTED_AT        TIMESTAMP_NTZ,
  APPROVER_SIGNATURE STRING,
  SOURCE             STRING    -- llm | template
);

-- Threat inbox: flagged domains, ranked by score then oldest flag, with the latest analyst label.
CREATE OR REPLACE VIEW GOLD.THREAT_INBOX AS
SELECT v.*, COALESCE(f.LABEL, 'UNREVIEWED') AS REVIEW_STATUS
FROM GOLD.DOMAIN_VERDICT v
LEFT JOIN (
  SELECT DOMAIN, COMPANY_ID, LABEL FROM SILVER.ANALYST_FEEDBACK
  QUALIFY ROW_NUMBER() OVER (PARTITION BY DOMAIN, COMPANY_ID ORDER BY FEEDBACK_AT DESC) = 1
) f ON f.DOMAIN = v.DOMAIN AND f.COMPANY_ID = v.COMPANY_ID
WHERE v.CLASSIFICATION IN ('SUSPICIOUS', 'HIGH_RISK', 'DANGEROUS')
ORDER BY v.SCORE DESC, v.FIRST_FLAGGED_AT ASC;

-- Lead time: first flag against first listing. A later listing does not prove malice at flag time.
CREATE OR REPLACE VIEW GOLD.LEAD_TIME AS
SELECT DOMAIN, COMPANY_ID, FIRST_FLAGGED_AT, FIRST_LISTED_AT,
       ROUND(DATEDIFF('second', FIRST_FLAGGED_AT, FIRST_LISTED_AT) / 3600, 2) AS LEAD_TIME_HOURS,
       CASE WHEN FIRST_LISTED_AT IS NULL THEN 'NOT_LISTED_YET'
            WHEN FIRST_LISTED_AT > FIRST_FLAGGED_AT THEN 'FLAGGED_BEFORE_LISTING'
            ELSE 'LISTED_BEFORE_FLAG' END AS STATUS
FROM GOLD.DOMAIN_VERDICT
WHERE FIRST_FLAGGED_AT IS NOT NULL;
