-- DomainGuard v7 / 03: Silver, cleaned data. Dynamic tables refresh from Bronze every 15 minutes.
-- Scoring-job outputs (features, breakdown, analyst feedback) are plain tables.
USE DATABASE DOMAINGUARD;

CREATE OR REPLACE DYNAMIC TABLE SILVER.PARSED_DOMAINS
  TARGET_LAG = '15 minutes' WAREHOUSE = DG_WH
AS
SELECT DOMAIN, MIN(SEEN_AT) AS FIRST_SEEN, MAX(SEEN_AT) AS LAST_SEEN, COUNT(*) AS CERT_COUNT
FROM BRONZE.CERTSTREAM_EVENTS
GROUP BY DOMAIN;

-- Earliest known listing per host: the feed's own listing time, else when we first observed it.
CREATE OR REPLACE DYNAMIC TABLE SILVER.CLEAN_BLOCKLIST
  TARGET_LAG = '15 minutes' WAREHOUSE = DG_WH
AS
SELECT DOMAIN,
       MIN(COALESCE(LISTED_AT, OBSERVED_AT)) AS LISTED_AT,
       LISTAGG(DISTINCT SOURCE, ',') AS SOURCES
FROM BRONZE.BLOCKLIST_FEED
GROUP BY DOMAIN;

-- Latest registration date per domain. Unknown domains simply have no row.
CREATE OR REPLACE DYNAMIC TABLE SILVER.RDAP_AGE
  TARGET_LAG = '15 minutes' WAREHOUSE = DG_WH
AS
SELECT DOMAIN, MAX(REGISTERED_AT) AS REGISTERED_AT
FROM BRONZE.RDAP_RESPONSES
WHERE HTTP_STATUS = 200 AND REGISTERED_AT IS NOT NULL
GROUP BY DOMAIN;

-- One row per (domain, company, factor): every point is auditable.
CREATE TABLE IF NOT EXISTS SILVER.SCORE_BREAKDOWN (
  DOMAIN          STRING,
  COMPANY_ID      STRING,
  FACTOR          STRING,
  POINTS          NUMBER,
  EVALUATED_AT    TIMESTAMP_NTZ,
  SCORING_VERSION STRING
);

-- Append-only analyst labels. Never UPDATE or DELETE.
CREATE TABLE IF NOT EXISTS SILVER.ANALYST_FEEDBACK (
  DOMAIN         STRING,
  COMPANY_ID     STRING,
  ANALYST_EMAIL  STRING,
  LABEL          STRING,        -- CONFIRMED_THREAT | FALSE_POSITIVE
  NOTE           STRING,
  FEEDBACK_AT    TIMESTAMP_NTZ DEFAULT SYSDATE()
);
