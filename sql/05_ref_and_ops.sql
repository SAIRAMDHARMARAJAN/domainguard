-- DomainGuard v7 / 05: reference data (companies and protected domains) and operations tables.
USE DATABASE DOMAINGUARD;

CREATE TABLE IF NOT EXISTS REF.USERS (
  COMPANY_ID            STRING PRIMARY KEY,
  NAME                  STRING NOT NULL,
  EMAIL                 STRING NOT NULL,
  CONTACT_PERSON        STRING,
  CREATED_AT            TIMESTAMP_NTZ DEFAULT SYSDATE(),
  STATUS                STRING DEFAULT 'PENDING',   -- PENDING | ACTIVE | SUSPENDED | DELETED
  API_KEY_HASH          STRING,                     -- SHA-256 of the key; the key itself is never stored
  API_KEY_CREATED_AT    TIMESTAMP_NTZ,
  DISPUTE_CONTACT       STRING,
  EMAIL_NOTIFICATIONS   BOOLEAN DEFAULT TRUE,
  NOTIFICATION_EMAIL    STRING,
  LAST_LOGIN_AT         TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS REF.PROTECTED_DOMAINS (
  COMPANY_ID       STRING,
  DOMAIN           STRING,
  BRAND_ALIASES    STRING,       -- comma-separated
  OFFICIAL_DOMAIN_1 STRING,
  OFFICIAL_DOMAIN_2 STRING,
  OFFICIAL_DOMAIN_3 STRING,
  ADDED_AT         TIMESTAMP_NTZ DEFAULT SYSDATE(),
  VERIFIED         BOOLEAN DEFAULT FALSE,
  STATUS           STRING DEFAULT 'ACTIVE',      -- ACTIVE | REMOVED
  PRIMARY KEY (COMPANY_ID, DOMAIN)
);

CREATE TABLE IF NOT EXISTS OPS.REGISTRATION_VERIFICATION (
  COMPANY_ID          STRING,
  EMAIL               STRING,
  VERIFICATION_TOKEN  STRING PRIMARY KEY,  -- SHA-256 of the emailed token
  CREATED_AT          TIMESTAMP_NTZ DEFAULT SYSDATE(),
  EXPIRES_AT          TIMESTAMP_NTZ,
  VERIFIED_AT         TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS OPS.LOAD_LOG (
  FILE_NAME    STRING PRIMARY KEY,   -- path of the staged file, relative to the stage root
  SOURCE       STRING,
  ROW_COUNT    NUMBER,
  BYTES        NUMBER,
  SHA256       STRING,
  LOADED_AT    TIMESTAMP_NTZ DEFAULT SYSDATE(),
  STATUS       STRING                -- SUCCESS | FAILED | SKIPPED
);

CREATE TABLE IF NOT EXISTS OPS.EMAIL_LOG (
  EMAIL_ID         STRING PRIMARY KEY,
  COMPANY_ID       STRING,
  DOMAIN           STRING,
  RECIPIENT_EMAIL  STRING,
  VERDICT_SCORE    NUMBER,
  CLASSIFICATION   STRING,
  SENT_AT          TIMESTAMP_NTZ DEFAULT SYSDATE(),
  STATUS           STRING DEFAULT 'SENT',   -- SENT | FAILED | BOUNCED
  ERROR_MESSAGE    STRING,
  KIND             STRING                   -- ALERT | DIGEST
);

CREATE TABLE IF NOT EXISTS OPS.EMAIL_PREFERENCES (
  COMPANY_ID              STRING PRIMARY KEY,
  EMAIL_NOTIFICATIONS     BOOLEAN DEFAULT TRUE,
  NOTIFICATION_FREQUENCY  STRING DEFAULT 'IMMEDIATE',   -- IMMEDIATE | DAILY | WEEKLY
  MIN_SCORE_THRESHOLD     NUMBER DEFAULT 70,
  NOTIFICATION_EMAIL      STRING,
  FREQUENCY_LAST_SENT_AT  TIMESTAMP_NTZ
);

CREATE TABLE IF NOT EXISTS OPS.EVALUATION_METRICS (
  METRIC_DATE        DATE,
  COMPANY_ID         STRING,
  PRECISION          FLOAT,
  RECALL             FLOAT,
  LEAD_TIME_MEDIAN   FLOAT,
  LEAD_TIME_P25      FLOAT,
  LEAD_TIME_P75      FLOAT,
  DOMAINS_FLAGGED    NUMBER,
  CONFIRMED_THREATS  NUMBER,
  FALSE_POSITIVES    NUMBER,
  ANALYST_HOURS      FLOAT,
  PRIMARY KEY (METRIC_DATE, COMPANY_ID)
);
