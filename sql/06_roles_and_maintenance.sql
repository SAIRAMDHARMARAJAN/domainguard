-- DomainGuard v7 / 06: roles (least privilege) and Bronze retention.
-- DEVIATION from the specification's "DG_API read-only Gold": registration, email verification and company settings
-- must write to REF and OPS, so DG_API gets Gold read plus write on exactly those tables. Nothing else.
USE DATABASE DOMAINGUARD;

CREATE ROLE IF NOT EXISTS DG_PIPELINE;   -- collectors, loader, scoring job, explanation worker, notifier
CREATE ROLE IF NOT EXISTS DG_API;        -- public API
CREATE ROLE IF NOT EXISTS DG_ANALYST;    -- dashboard
CREATE ROLE IF NOT EXISTS DG_ADMIN;      -- setup only

GRANT USAGE ON WAREHOUSE DG_WH TO ROLE DG_PIPELINE;
GRANT USAGE ON WAREHOUSE DG_WH TO ROLE DG_API;
GRANT USAGE ON WAREHOUSE DG_WH TO ROLE DG_ANALYST;
GRANT USAGE ON DATABASE DOMAINGUARD TO ROLE DG_PIPELINE;
GRANT USAGE ON DATABASE DOMAINGUARD TO ROLE DG_API;
GRANT USAGE ON DATABASE DOMAINGUARD TO ROLE DG_ANALYST;

-- Pipeline: fills Bronze, Silver, Gold and OPS; reads REF.
GRANT USAGE ON SCHEMA REF TO ROLE DG_PIPELINE;
GRANT USAGE ON SCHEMA BRONZE TO ROLE DG_PIPELINE;
GRANT USAGE ON SCHEMA SILVER TO ROLE DG_PIPELINE;
GRANT USAGE ON SCHEMA GOLD TO ROLE DG_PIPELINE;
GRANT USAGE ON SCHEMA OPS TO ROLE DG_PIPELINE;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA BRONZE TO ROLE DG_PIPELINE;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA BRONZE TO ROLE DG_PIPELINE;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA SILVER TO ROLE DG_PIPELINE;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA SILVER TO ROLE DG_PIPELINE;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA GOLD TO ROLE DG_PIPELINE;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA GOLD TO ROLE DG_PIPELINE;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA OPS TO ROLE DG_PIPELINE;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA OPS TO ROLE DG_PIPELINE;
GRANT SELECT ON ALL TABLES IN SCHEMA REF TO ROLE DG_PIPELINE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA REF TO ROLE DG_PIPELINE;
GRANT SELECT ON ALL DYNAMIC TABLES IN SCHEMA SILVER TO ROLE DG_PIPELINE;
GRANT SELECT ON FUTURE DYNAMIC TABLES IN SCHEMA SILVER TO ROLE DG_PIPELINE;
GRANT READ, WRITE ON STAGE BRONZE.DG_STAGE TO ROLE DG_PIPELINE;
GRANT USAGE ON FILE FORMAT BRONZE.DG_JSON TO ROLE DG_PIPELINE;

-- API: Gold read; REF and OPS writes only for registration and settings; no Bronze or Silver access.
GRANT USAGE ON SCHEMA GOLD TO ROLE DG_API;
GRANT USAGE ON SCHEMA REF TO ROLE DG_API;
GRANT USAGE ON SCHEMA OPS TO ROLE DG_API;
GRANT SELECT ON ALL TABLES IN SCHEMA GOLD TO ROLE DG_API;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GOLD TO ROLE DG_API;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA REF TO ROLE DG_API;
GRANT SELECT, INSERT, UPDATE ON FUTURE TABLES IN SCHEMA REF TO ROLE DG_API;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA OPS TO ROLE DG_API;
GRANT SELECT, INSERT, UPDATE ON FUTURE TABLES IN SCHEMA OPS TO ROLE DG_API;

-- Analysts: read Gold and Silver; append feedback; work on takedown drafts; record metrics.
GRANT USAGE ON SCHEMA GOLD TO ROLE DG_ANALYST;
GRANT USAGE ON SCHEMA SILVER TO ROLE DG_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA GOLD TO ROLE DG_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA GOLD TO ROLE DG_ANALYST;
GRANT SELECT ON ALL VIEWS IN SCHEMA GOLD TO ROLE DG_ANALYST;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA GOLD TO ROLE DG_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA SILVER TO ROLE DG_ANALYST;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SILVER TO ROLE DG_ANALYST;
GRANT INSERT ON TABLE SILVER.ANALYST_FEEDBACK TO ROLE DG_ANALYST;           -- append only
GRANT SELECT, INSERT, UPDATE ON TABLE GOLD.TAKEDOWN_DRAFTS TO ROLE DG_ANALYST;

-- Retention: 30 days of certificate and feed data, 90 days of RDAP. The load log is never purged.
CREATE OR REPLACE PROCEDURE OPS.PURGE_BRONZE()
RETURNS STRING LANGUAGE SQL AS
$$
BEGIN
  DELETE FROM BRONZE.CERTSTREAM_EVENTS WHERE LOADED_AT < DATEADD('day', -30, SYSDATE());
  DELETE FROM BRONZE.BLOCKLIST_FEED    WHERE LOADED_AT < DATEADD('day', -30, SYSDATE());
  DELETE FROM BRONZE.RDAP_RESPONSES    WHERE LOADED_AT < DATEADD('day', -90, SYSDATE());
  RETURN 'purged';
END;
$$;

CREATE OR REPLACE TASK OPS.PURGE_BRONZE_TASK
  WAREHOUSE = DG_WH
  SCHEDULE = 'USING CRON 0 2 * * * UTC'
AS CALL OPS.PURGE_BRONZE();
-- Tasks are created suspended. Enable when ready:  ALTER TASK OPS.PURGE_BRONZE_TASK RESUME;
